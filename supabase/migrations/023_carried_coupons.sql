--  023  목표 초과분 쿠폰 이월
--   목표를 채운 뒤 데스크에 가기 전까지 더 모은 쿠폰이 초기화로 사라지지 않도록,
--   상품 지급 시 초과분을 이 칸에 남겨 다음 판으로 넘긴다.
--   선생님이 주는 특별 쿠폰(bonus_coupons)과는 구분해야 한다.
--   특별 쿠폰은 학생 화면에 보라색 테두리로 표시되지만, 이월분은 평범한
--   쿠폰으로 보여야 하고 선생님의 특별 쿠폰 +/− 대상도 아니기 때문이다.
-- ============================================================

alter table public.students
  add column if not exists carried_coupons int not null default 0;
